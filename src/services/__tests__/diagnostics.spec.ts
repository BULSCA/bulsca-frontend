import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
describe('best-effort diagnostics', () => {
  beforeEach(() => { vi.resetModules(); vi.useFakeTimers(); vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true) })
  afterEach(() => { vi.clearAllTimers(); vi.useRealTimers(); vi.restoreAllMocks(); vi.unstubAllGlobals() })

  it('sends bounded safe context and deduplicates repeated failures', async () => {
    const fetch = vi.fn<typeof globalThis.fetch>().mockResolvedValue(new Response('', { status: 202 }))
    vi.stubGlobal('fetch', fetch)
    const { reportError, flushReports } = await import('../diagnostics')
    reportError('network', '/article/:slug')
    reportError('network', '/article/:slug')
    await flushReports()
    expect(fetch).toHaveBeenCalledTimes(1)
    const payload = JSON.parse(String(fetch.mock.calls[0]![1]?.body))
    expect(payload.message).toBe('Request failed')
    expect(payload.route_template).toBe('/article/:slug')
    expect(payload).not.toHaveProperty('stack')
  })
  it('caps the offline queue at twenty and retries only after reconnect', async () => {
    vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(false)
    const fetch = vi.fn<typeof globalThis.fetch>().mockResolvedValue(new Response('', { status: 202 }))
    vi.stubGlobal('fetch', fetch)
    const { reportError, flushReports } = await import('../diagnostics')
    for (let i = 0; i < 25; i++) reportError('network', `/page${i}`)
    await flushReports()
    expect(fetch).not.toHaveBeenCalled()
    vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true)
    await flushReports()
    expect(fetch).toHaveBeenCalledTimes(20)
  })
  it('drops expired reports and never includes sensitive URLs', async () => {
    const fetch = vi.fn<typeof globalThis.fetch>().mockResolvedValue(new Response('', { status: 202 }))
    vi.stubGlobal('fetch', fetch)
    const { reportError, flushReports } = await import('../diagnostics')
    reportError('route', '/article?token=private')
    await flushReports()
    expect(String(fetch.mock.calls[0]![1]?.body)).not.toContain('private')
    reportError('network', '/expired')
    vi.setSystemTime(Date.now() + 31 * 60 * 1000)
    await flushReports()
    expect(fetch).toHaveBeenCalledTimes(1)
  })
  it('backs off failed reports without recursively reporting them', async () => {
    const fetch = vi.fn<typeof globalThis.fetch>().mockRejectedValue(new Error('offline'))
    vi.stubGlobal('fetch', fetch)
    const { reportError, flushReports } = await import('../diagnostics')
    reportError('server', '/latest', 503)
    await flushReports()
    expect(fetch).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(0)
    expect(fetch.mock.calls.length).toBeLessThanOrEqual(2)
  })
})
